/**
 * QR Code Types
 *
 * Data structures for QR code generation and scanning.
 * Shared between web (generation) and mobile (scanning).
 */

/**
 * QR Code data structure expected by the scanner
 */
export interface QRCodeData {
  orderId: string;
  eventId: string;
  userId?: string;
  tierName?: string;
  eventName?: string;
  ticketNumber: number;
  qrToken: string;
  timestamp: string;
}

/**
 * Result of QR code format validation
 */
export interface QRCodeValidationResult {
  valid: boolean;
  errors: string[];
}

/**
 * Validate QR code format matches scanner expectations
 * This ensures QR codes generated by purchase API routes are compatible with the scanner
 *
 * @param qrData - QR code data object to validate
 * @returns Validation result with errors array
 */
export function validateQRCodeFormat(qrData: unknown): QRCodeValidationResult {
  const errors: string[] = [];

  // Type guard: ensure qrData is an object
  if (typeof qrData !== "object" || qrData === null) {
    return {
      valid: false,
      errors: ["Invalid QR data: expected object"],
    };
  }

  const data = qrData as Record<string, unknown>;

  // Required fields for scanner
  if (!data.orderId) errors.push("Missing orderId");
  if (!data.eventId) errors.push("Missing eventId");
  if (data.ticketNumber === undefined) errors.push("Missing ticketNumber");
  if (!data.qrToken) errors.push("Missing qrToken");

  // Validate timestamp: required and must be a valid ISO-8601 date
  if (!data.timestamp) {
    errors.push("Missing timestamp");
  } else if (typeof data.timestamp !== "string") {
    errors.push("timestamp must be a string");
  } else {
    const parsedTimestamp = Date.parse(data.timestamp);
    if (isNaN(parsedTimestamp)) {
      errors.push("timestamp must be a valid ISO-8601 date string");
    }
  }

  // Check for old format fields (should NOT exist)
  const oldFormatFields = [
    "ticket_id",
    "event_id",
    "tier_id",
    "attendee_email",
  ];
  for (const field of oldFormatFields) {
    if (field in data) {
      errors.push(`Found old format field: ${field} (should not be present)`);
    }
  }

  // Validate specific field formats
  if (data.orderId && data.orderId === "PLACEHOLDER") {
    errors.push("orderId should not be 'PLACEHOLDER' in final QR code");
  }

  if (data.ticketNumber !== undefined && (data.ticketNumber as number) < 1) {
    errors.push("ticketNumber should be >= 1");
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}
