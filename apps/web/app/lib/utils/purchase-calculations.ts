/**
 * Utility functions for purchase flow calculations
 * These functions are used across the purchase flow and are tested to ensure consistency
 */

/**
 * Calculate the unit price for a ticket purchase
 * Uses stage pricing if available, otherwise falls back to tier base price
 *
 * @param mode - Purchase mode: "rsvp" or "hold"
 * @param rsvpDetails - RSVP details with optional stage_price_cents and ticket_tier
 * @param holdDetails - Hold details with optional stage_price_cents and ticket_tier
 * @param ticketTier - Optional ticket tier with base price_cents (for backward compatibility with tests)
 * @returns Unit price in cents
 */
export function calculateUnitPrice(
  mode: "rsvp" | "hold" | null,
  rsvpDetails: { stage_price_cents?: number | null; ticket_tier?: { price_cents: number } } | null,
  holdDetails: { stage_price_cents?: number | null; ticket_tier?: { price_cents: number } } | null,
  ticketTier?: { price_cents: number }
): number {
  if (!mode) return 0;

  // Use stage pricing if available (prioritized over tier base price)
  if (mode === "rsvp" && rsvpDetails?.stage_price_cents != null) {
    return rsvpDetails.stage_price_cents;
  }
  if (mode === "hold" && holdDetails?.stage_price_cents != null) {
    return holdDetails.stage_price_cents;
  }

  // Fallback to tier price from details or provided ticketTier
  const tier = mode === "rsvp" ? rsvpDetails?.ticket_tier : holdDetails?.ticket_tier;
  return tier?.price_cents ?? ticketTier?.price_cents ?? 0;
}

/**
 * QR Code data structure expected by the scanner
 */
export interface QRCodeData {
  orderId: string;
  eventId: string;
  userId?: string;
  tierName?: string;
  eventName?: string;
  ticketNumber: number;
  qrToken: string;
  timestamp: string;
}

/**
 * Validate QR code format matches scanner expectations
 * This ensures QR codes generated by purchase API routes are compatible with the scanner
 *
 * @param qrData - QR code data object to validate
 * @returns Validation result with errors array
 */
export function validateQRCodeFormat(qrData: any): {
  valid: boolean;
  errors: string[];
} {
  const errors: string[] = [];

  // Required fields for scanner
  if (!qrData.orderId) errors.push("Missing orderId");
  if (!qrData.eventId) errors.push("Missing eventId");
  if (qrData.ticketNumber === undefined) errors.push("Missing ticketNumber");
  if (!qrData.qrToken) errors.push("Missing qrToken");

  // Check for old format fields (should NOT exist)
  const oldFormatFields = [
    "ticket_id",
    "event_id",
    "tier_id",
    "attendee_email",
  ];
  for (const field of oldFormatFields) {
    if (field in qrData) {
      errors.push(`Found old format field: ${field} (should not be present)`);
    }
  }

  // Validate specific field formats
  if (qrData.orderId && qrData.orderId === "PLACEHOLDER") {
    errors.push("orderId should not be 'PLACEHOLDER' in final QR code");
  }

  if (qrData.ticketNumber !== undefined && qrData.ticketNumber < 1) {
    errors.push("ticketNumber should be >= 1");
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

